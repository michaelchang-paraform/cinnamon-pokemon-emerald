import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dataUrl, encodePng } from '../lib/png.mjs';
import { readIndexedPng } from '../partners/png-read.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const EXT = join(HERE, '..', '..', 'extension-theme');
const SRC = join(HERE, 'download', 'pret', 'pokeemerald');
const LIMIT = 500 * 1024;
const { items } = JSON.parse(readFileSync(join(HERE, 'items.json'), 'utf8'));

// a 24x24 bag icon in its own palette; index 0 is transparent
function icon(item) {
  const img = readIndexedPng(readFileSync(join(SRC, item.icon)));
  const colors = readFileSync(join(SRC, item.palette), 'utf8').trim().split(/\r?\n/).slice(3)
    .map((line) => line.trim().split(/\s+/).map(Number).map((v) => v.toString(16).padStart(2, '0')).join(''));
  return Array.from({ length: img.height }, (_, y) => Array.from({ length: img.width }, (_, x) => {
    const at = img.index[y * img.width + x];
    return at ? colors[at] : null;
  }));
}

const png = (grid) => encodePng(grid[0].length, grid.length, (x, y) => (grid[y][x] ? `#${grid[y][x]}` : null));
const url = (grid) => `url("${dataUrl(png(grid))}")`;
const sizes = [];
const write = (name, text) => {
  writeFileSync(join(EXT, name), text);
  sizes.push(`${name} ${(text.length / 1024).toFixed(1)} KB`);
  if (text.length > LIMIT) throw new Error(`${name} is over 500 KB`);
};

const full = new Map();
for (const item of items) {
  const grid = icon(item);
  if (!full.has(item.pocket)) full.set(item.pocket, []);
  full.get(item.pocket).push(`--pe-item-${item.id}: ${url(grid)};`);
}
// the icons resolve only on the picker and the icon buttons, so only the ones shown get decoded
for (const [pocket, vars] of full) write(`items-${pocket}.css`, `.pe-ball-menu, .pe-ball-btn, .pe-icon-pick > span:first-child { ${vars.join(' ')} }\n`);

const rows = items.map((item) => `  [${JSON.stringify(item.id)}, ${JSON.stringify(item.name)}, ${JSON.stringify(item.pocket)}],`);
write('items.ts', `// generated by source/sprites/build-items.mjs from pret/pokeemerald: id, bag name, bag pocket\nexport const ITEMS: readonly (readonly [string, string, string])[] = [\n${rows.join('\n')}\n];\n`);
console.log(`${items.length} items\n${sizes.join('\n')}`);
